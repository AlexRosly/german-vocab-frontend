// Locale helpers are independent of React so validation and formatting can be tested directly.
export const UI_LANGUAGES = [
  { code: "ru", label: "Русский" }, { code: "de", label: "Deutsch" },
  { code: "en", label: "English" }, { code: "uk", label: "Українська" },
] as const;
export type UiLanguage = typeof UI_LANGUAGES[number]["code"];
export const UI_LANGUAGE_STORAGE_KEY = "wortkarten-interface-language";
export function isUiLanguage(value: unknown): value is UiLanguage {
  return UI_LANGUAGES.some((entry) => entry.code === value);
}
export function uiLanguage(value: unknown): UiLanguage { return isUiLanguage(value) ? value : "ru"; }
export const UI_LOCALES: Record<UiLanguage, string> = { ru: "ru-RU", de: "de-DE", en: "en-GB", uk: "uk-UA" };
export type MessageParams = Readonly<Record<string, string | number>>;
const catalog: Readonly<Record<string, Readonly<Record<"de" | "en" | "uk", string>>>> = MESSAGES;
const placeholders = /\{([a-zA-Z0-9_]+)\}/g;
const escape = (value: string) => value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const patterns = Object.keys(catalog).filter((key) => /\{[a-zA-Z0-9_]+\}/.test(key)).map((key) => {
  const names = [...key.matchAll(placeholders)].map((match) => match[1]);
  return { key, names, regex: new RegExp("^" + key.split(/\{[a-zA-Z0-9_]+\}/).map(escape).join("([\\s\\S]*?)") + "$") };
});
function resolve(source: string): { key: string; params: MessageParams } | null {
  if (Object.hasOwn(catalog, source)) return { key: source, params: {} };
  for (const pattern of patterns) {
    const match = pattern.regex.exec(source);
    if (match) return { key: pattern.key, params: Object.fromEntries(pattern.names.map((name, index) => [name, match[index + 1]])) };
  }
  return null;
}

// Only UI-owned messages pass through this function; vocabulary and user text are rendered directly.
export function translate(language: UiLanguage, source: string, params?: MessageParams): string {
  const resolved = resolve(source);
  if (!resolved) return source;
  if (resolved.key === "Начинаем тренировку: {0} новых слов." && !params) {
    return translate(language, "Начинаем тренировку: {count}.", { count: counted(language, Number(resolved.params[0])) });
  }
  const template = language === "ru" ? (source === "DEUTSCH LERNEN" ? "УЧИМ НЕМЕЦКИЙ" : resolved.key) : catalog[resolved.key][language];
  let values = params ?? resolved.params;
  if (!params && ["Не удалось сохранить: {0}", "Тренировка завершена, но сохранить результаты не удалось: {0}"].includes(resolved.key)) {
    values = { ...values, 0: translate(language, safeErrorMessage(values[0])) };
  }
  return template.replace(placeholders, (match, name: string) => String(values[name] ?? match));
}

export function safeErrorMessage(error: unknown, fallback = "Не удалось выполнить запрос. Повторите попытку."): string {
  const value = error && typeof error === "object" ? error as { message?: unknown; status?: unknown } : null;
  const message = typeof error === "string" ? error : typeof value?.message === "string" ? value.message : "";
  if (resolve(message)) return message;
  const defaults: Record<string, string> = { "Internal server error": "Ошибка сервера. Повторите попытку позже.", Unauthorized: "Сессия завершена. Войдите снова.", Forbidden: "Действие недоступно для этого аккаунта.", "Too Many Requests": "Слишком много запросов. Подождите и попробуйте снова." };
  if (Object.hasOwn(defaults, message)) return defaults[message];
  if (message && /(?:must (?:be|contain|have)|should not|isEmail|is not allowed)/i.test(message)) return "Проверьте введённые данные.";
  const status = value?.status;
  if (status === 400) return "Проверьте введённые данные.";
  if (status === 401) return "Сессия завершена. Войдите снова.";
  if (status === 403) return "Действие недоступно для этого аккаунта.";
  if (status === 404) return "Карточка не найдена";
  if (status === 409) return "Данные изменились. Обновите страницу и повторите действие.";
  if (status === 429) return "Слишком много запросов. Подождите и попробуйте снова.";
  if (typeof status === "number" && status >= 500) return "Ошибка сервера. Повторите попытку позже.";
  return fallback;
}

type Noun = "word" | "card" | "day";
const nouns: Record<UiLanguage, Record<Noun, { one: string; few?: string; many?: string; other: string }>> = {
  ru: { word: { one: "слово", few: "слова", many: "слов", other: "слова" }, card: { one: "карточка", few: "карточки", many: "карточек", other: "карточки" }, day: { one: "день", few: "дня", many: "дней", other: "дня" } },
  uk: { word: { one: "слово", few: "слова", many: "слів", other: "слова" }, card: { one: "картка", few: "картки", many: "карток", other: "картки" }, day: { one: "день", few: "дні", many: "днів", other: "дня" } },
  de: { word: { one: "Wort", other: "Wörter" }, card: { one: "Karte", other: "Karten" }, day: { one: "Tag", other: "Tage" } },
  en: { word: { one: "word", other: "words" }, card: { one: "card", other: "cards" }, day: { one: "day", other: "days" } },
};
export function noun(language: UiLanguage, count: number, kind: Noun): string {
  const forms = nouns[language][kind];
  const category = new Intl.PluralRules(UI_LOCALES[language]).select(count);
  return forms[category as keyof typeof forms] ?? forms.other;
}
export function counted(language: UiLanguage, count: number, kind: Noun = "word"): string {
  return `${new Intl.NumberFormat(UI_LOCALES[language]).format(count)} ${noun(language, count, kind)}`;
}
export function formatDate(language: UiLanguage, value: string): string {
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return translate(language, "Нет данных");
  return new Intl.DateTimeFormat(UI_LOCALES[language], { dateStyle: "medium", timeStyle: "short" }).format(date);
}
export function createI18n(language: UiLanguage) {
  return {
    language, locale: UI_LOCALES[language],
    t: (source: string, params?: MessageParams) => translate(language, source, params),
    errorText: (error: unknown) => translate(language, safeErrorMessage(error)),
    count: (value: number, kind: Noun = "word") => counted(language, value, kind),
    noun: (value: number, kind: Noun) => noun(language, value, kind),
    date: (value: string) => formatDate(language, value),
  };
}
